"""Read-only PE inspection. Writes reports/profile only to explicit output paths."""
import argparse
import hashlib
import json
import pathlib
import struct

def inspect(path):
    data = pathlib.Path(path).read_bytes()
    if data[:2] != b"MZ":
        raise ValueError("Not a Windows executable")
    pe = struct.unpack_from("<I", data, 0x3c)[0]
    if data[pe:pe+4] != b"PE\0\0" or struct.unpack_from("<H", data, pe+4)[0] != 0x8664:
        raise ValueError("Expected an x64 PE executable")
    count = struct.unpack_from("<H", data, pe+6)[0]
    timestamp = struct.unpack_from("<I", data, pe+8)[0]
    optional = pe+24
    if struct.unpack_from("<H", data, optional)[0] != 0x20b:
        raise ValueError("Expected PE32+")
    image_size = struct.unpack_from("<I", data, optional+56)[0]
    table = optional + struct.unpack_from("<H", data, pe+20)[0]
    sections = []
    for i in range(count):
        offset = table+40*i
        name = data[offset:offset+8].rstrip(b"\0").decode("ascii")
        _, rva, size, raw = struct.unpack_from("<IIII", data, offset+8)
        if raw+size > len(data):
            raise ValueError("Truncated section")
        sections.append((name, rva, size, raw))
    functions = []
    for name, _, size, raw in sections:
        if name == ".pdata":
            for offset in range(raw, raw+size-11, 12):
                start, end, _ = struct.unpack_from("<III", data, offset)
                if start < end:
                    functions.append((start, end))
    candidates = []
    marker = bytes.fromhex("8b0283f80a")
    for name, rva, size, raw in sections:
        if name != ".text":
            continue
        section = data[raw:raw+size]
        position = 0
        while (position := section.find(marker, position)) >= 0:
            address = rva+position
            bounds = [(start,end) for start,end in functions if start <= address < end]
            for start, end in bounds:
                # Validate the observed full function entry and marker relationship.
                entry = section[start-rva:start-rva+32]
                if address-start == 0x52 and entry.startswith(bytes.fromhex("405556574154415541564157")):
                    candidates.append((start, end, entry.hex()))
            position += 1
    if len(candidates) != 1:
        raise ValueError(f"Expected one award candidate, found {len(candidates)}; no profile generated")
    start, end, prologue = candidates[0]
    return {"sha256": hashlib.sha256(data).hexdigest(), "file_size": len(data),
            "pe_timestamp": timestamp, "image_size": image_size,
            "award_rva": start, "award_end_rva": end, "prologue_hex": prologue,
            "status": "offline candidate; live semantics and source classification unverified"}

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("exe")
    parser.add_argument("--report", type=pathlib.Path)
    parser.add_argument("--header", type=pathlib.Path)
    args = parser.parse_args()
    report = inspect(args.exe)
    serialized = json.dumps(report, indent=2)+"\n"
    print(serialized, end="")
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(serialized)
    if args.header:
        expected = ", ".join("0x"+report["prologue_hex"][i:i+2] for i in range(0,64,2))
        args.header.write_text(
            "// Generated by scripts/inspect_game.py from the local executable.\n"
            "// Candidate only: do not regenerate for a new build without reviewing disassembly.\n"
            "#pragma once\n#include <cstdint>\nnamespace shared_loot::profile {\n"
            f'inline constexpr char sha256[] = "{report["sha256"]}";\n'
            f'inline constexpr std::uint32_t timestamp = {report["pe_timestamp"]}u;\n'
            f'inline constexpr std::uint32_t image_size = {report["image_size"]}u;\n'
            f'inline constexpr std::uint32_t award_rva = {report["award_rva"]}u;\n'
            f'inline constexpr unsigned char prologue[32] = {{{expected}}};\n' + "}\n")
